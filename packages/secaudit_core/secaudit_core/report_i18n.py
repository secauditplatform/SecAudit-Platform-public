def resolve_report_locale(
    locale: str | None = None,
    *,
    accept_language: str | None = None,
) -> str:
    """Explicit locale query param, then Accept-Language, then English default."""
    if locale and locale.strip():
        return normalize_report_locale(locale)
    if accept_language:
        for item in accept_language.split(","):
            tag = item.strip().split(";")[0].strip()
            if not tag:
                continue
            code = tag.lower().replace("_", "-").split("-", 1)[0]
            if code in _STRINGS:
                return code
    return DEFAULT_REPORT_LOCALE


def normalize_report_locale(locale: str | None) -> str:
    if not locale:
        return DEFAULT_REPORT_LOCALE
    code = locale.strip().lower().replace("_", "-")
    primary = code.split("-", 1)[0]
    if primary in _STRINGS:
        return primary
    return "en"


def get_report_strings(locale: str | None) -> dict[str, str]:
    code = normalize_report_locale(locale)
    return dict(_STRINGS.get(code, _EN))


def status_labels_for_locale(locale: str | None, *, for_pdf: bool) -> dict[str, str]:
    del for_pdf
    t = get_report_strings(locale)
    return {
        "pass": t["status_pass"],
        "fail": t["status_fail"],
        "skip": t["status_skip"],
        "error": t["status_error"],
    }


def run_status_label(status: str, locale: str | None) -> str:
    t = get_report_strings(locale)
    key = {
        "pending": "run_pending",
        "queued": "run_queued",
        "running": "run_running",
        "completed": "run_completed",
        "failed": "run_failed",
        "cancelled": "run_cancelled",
        "canceled": "run_cancelled",
    }.get(status.lower())
    if key is None:
        return status.upper()
    return t[key]
